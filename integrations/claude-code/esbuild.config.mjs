// Build definition for the mubit-memory Claude Code plugin — build-guide §11.2.
//
// Everything Claude Code executes is a bundled, dependency-free .mjs: `node <path>` on a
// single file is a ~30 ms cold start, where `npx` or a TS loader would cost ~500 ms on
// every PostToolUse (§11.4). The output lives in git (§11.3), so the settings that make
// the build byte-reproducible — minify: false, sourcemap: 'inline' — are pinned here
// rather than left to esbuild's defaults; CI rebuilds and runs `git diff --exit-code`.

import { build, context } from 'esbuild';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const has = (rel) => existsSync(resolve(ROOT, rel));

// Where the build WRITES. Inputs always come from `ROOT`; only the outputs move.
//
// `MUBIT_CC_BUILD_OUTDIR` exists for one caller: the freshness gate, which rebuilds into a
// temp directory and compares the result byte-for-byte with the committed bundles. `npm test`
// runs `hooks/src` while the host runs the committed `hooks/dist`, so without that comparison
// a stale bundle passes the entire suite — which is exactly how a rejected field shipped in a
// launcher that no test had ever executed.
const OUT = process.env.MUBIT_CC_BUILD_OUTDIR ? resolve(process.env.MUBIT_CC_BUILD_OUTDIR) : ROOT;
const out = (rel) => resolve(OUT, rel);
const readJson = (rel) => JSON.parse(readFileSync(resolve(ROOT, rel), 'utf8'));

const shared = {
  bundle: true, platform: 'node', target: 'node20', format: 'esm',
  minify: false,            // readable stack traces beat 40 KB; nothing ships over a network
  sourcemap: 'inline', legalComments: 'none', logLevel: 'info',
  banner: { js: '// mubit-memory — generated by esbuild. Do not edit; edit hooks/src or lib.' },
};

// `drain`, `recall-refresh` and `session-resume` are absent from `hooks.json` on purpose —
// they are spawned detached, by `stage-prompt`/`capture`, by `prompt-recall` and by
// `session-start` respectively — but they are still exec'd by path, so they need the same
// launcher and the same runtime floor.
const HOOKS = ['session-start','cwd-changed','prompt-recall','stage-prompt','pre-tool','subagent-start','capture','checkpoint','session-end','drain','recall-refresh','session-resume'];

/**
 * The bundled @mubit-ai/mcp server (§8.3) — the **in-repo** package, not the registry copy.
 *
 * This used to read `node_modules/@mubit-ai/mcp/dist/index.js`, which resolved to whatever
 * npm had installed for `"@mubit-ai/mcp": "^0.8.0"`. The §8.1 allowlist patch landed after
 * 0.8.0 and was never published, so the shipped server did not read `MUBIT_MCP_TOOLS` at
 * all: the launcher set the variable, nothing consumed it, and every session paid for all
 * 21 tool schemas where ten were configured. Two correct halves that never met.
 *
 * The sibling is the honest input: it is the source this repo publishes `@mubit-ai/mcp`
 * from, `scripts/set-version.mjs` already holds the two versions in lockstep, and the
 * release guard already describes this plugin as built from the in-repo `@mubit-ai/mcp` it
 * dev-depends on. Building from the registry made that description false without anything
 * failing.
 *
 * It is TypeScript, so `dist/` here is `tsc` output rather than a tracked file, and must
 * exist before this runs — see the guard below `targets`.
 */
const MCP_SERVER_ENTRY = '../mcp/dist/index.js';

/** How to produce `MCP_SERVER_ENTRY`. Quoted in the error when it is missing. */
const MCP_SERVER_BUILD = 'npm --prefix ../mcp ci && npm --prefix ../mcp run build';

/**
 * The version stamped into the launcher as `__MUBIT_MCP_VERSION__`.
 *
 * The sibling manifest is the authority: it is the package `mcp/dist/server.js` was bundled
 * from. In the generated `claude-plugins` mirror that sibling does not exist — the mirror
 * carries this one plugin and vendors the server bundle — and reading it there threw at
 * module scope, which made `npm run build` unusable for every other target too.
 *
 * This plugin's own version is the right fallback rather than a guess: the two ship in
 * lockstep (`scripts/set-version.mjs` holds them together, and `manifests.test.mjs` enforces
 * three-way lockstep across the manifests), and `mcp-surface.test.mjs` already asserts the
 * server's advertised `serverInfo.version` equals this package's version — so the fallback
 * is checked by a test rather than assumed.
 */
const MCP_VERSION = has('../mcp/package.json')
  ? readJson('../mcp/package.json').version
  : readJson('package.json').version;

// ---------------------------------------------------------------------------
// The runtime floor guard (§11.1 engines)
// ---------------------------------------------------------------------------
// The bundles target node20 and use `??` ~40x per file. On an older Node they do not fail —
// they never load, and say nothing: no marker, no log line, no MCP activity, which reads
// exactly like a plugin that was never configured. A guard *inside* those bundles cannot
// help, because a module is parsed in full before its first statement executes; the parse
// error happens first. Nor can the target simply be lowered: all seven entry points use
// top-level await, and node14.8 is the lowest target esbuild will accept for it — still
// above the node12.22 that Debian 11 installs, and short of `fetch` (18+),
// `AbortController` (15+) and `Array.prototype.at` (16.6+) besides.
//
// So the file Claude Code actually executes is this launcher, built for an old runtime, and
// the real bundle moves to `impl/`. The launcher checks the version, and either refuses in a
// sentence or hands off. `hooks.json` and `settings.json` keep naming the same paths.
//
// LAUNCHER_TARGET is load-bearing twice over. It must be >= node12.20, or esbuild rewrites
// `import()` into `require()` and the launcher dies in ESM; and it is what mechanically
// guarantees this source stays parseable on old Node — esbuild fails the build if the
// launcher ever grows syntax that is too new, rather than leaving it to review.
const MIN_NODE_MAJOR = 20;
const LAUNCHER_TARGET = 'node12.20';

/**
 * @param {string} rel  impl path relative to the launcher, e.g. './impl/capture.mjs'
 * @param {string} what name used in the refusal message
 * @param {boolean} hookProtocol emit `{"suppressOutput":true}` on stdout — the hook contract
 *   (lib/hook.mjs: "stdout is ALWAYS a JSON object"). The status line writes a bare line
 *   instead, so for it, silence is the correct no-op.
 *
 * `__mubitLauncherEntry` exists for `bin/statusline.src.mjs`, which runs its body only when
 * it is the process entry — and behind a launcher it no longer literally is. The flag is
 * realm-local rather than an env var, which would leak into every child process a hook
 * spawns. The hook bundles do not consult it; they have no such guard.
 */
const launcher = (rel, what, hookProtocol) => `import { writeSync } from 'fs';
var major = parseInt(String(process.versions.node).split('.')[0], 10);
if (!(major >= ${MIN_NODE_MAJOR})) {
  try {
    writeSync(2, 'mubit-memory requires Node >= ${MIN_NODE_MAJOR} (package.json engines); found v'
      + process.versions.node + '. ${what} is disabled for this session.\\n');
${hookProtocol ? '    writeSync(1, \'{"suppressOutput":true}\');\n' : ''}  } catch (e) { /* a closed pipe is not worth failing a session over */ }
  // 0, never 1: a misconfigured runtime must not fail the user's session.
  process.exit(0);
}
globalThis.__mubitLauncherEntry = ${JSON.stringify(rel)};
import('${rel}').catch(function (err) {
  try {
    writeSync(2, 'mubit-memory: ${what} failed to load: '
      + ((err && err.message) ? err.message : String(err)) + '\\n');
${hookProtocol ? '    writeSync(1, \'{"suppressOutput":true}\');\n' : ''}  } catch (e) { /* ditto */ }
  process.exit(0);
});
`;

/** @param {string} contents @param {string} sourcefile @param {string} outfile */
const launcherTarget = (contents, sourcefile, outfile) => ({
  stdin: { contents, sourcefile, loader: /** @type {const} */ ('js'), resolveDir: ROOT },
  outfile: out(outfile),
  bundle: false,              // the one dynamic import must stay a runtime import, not inlined
  platform: /** @type {const} */ ('node'),
  format: /** @type {const} */ ('esm'),
  target: LAUNCHER_TARGET,
  minify: false, legalComments: /** @type {const} */ ('none'), logLevel: /** @type {const} */ ('info'),
  banner: { js: '// mubit-memory runtime floor guard — generated by esbuild. Do not edit.' },
});

const targets = [
  // outExtension is load-bearing: with `outdir`, esbuild names output `<entry>.js` no matter
  // what the entry was called, so hooks/src/capture.mjs becomes hooks/dist/capture.js while
  // hooks.json points at capture.mjs. Every hook silently becomes a dead path — the plugin
  // installs, registers ten hooks, and none of them exist. (Guide §11.2 omits this; the
  // `outfile` targets below are unaffected because they name the extension outright.)
  {
    entryPoints: HOOKS.map((n) => `hooks/src/${n}.mjs`),
    outdir: out('hooks/dist/impl'), outbase: 'hooks/src',
    outExtension: { '.js': '.mjs' },
    ...shared,
  },
  // The guards Claude Code actually executes — one per registered path, identical but for
  // the impl each hands off to.
  ...HOOKS.map((n) => launcherTarget(
    launcher(`./impl/${n}.mjs`, `hook ${n}`, true), `${n}.launcher.mjs`, `hooks/dist/${n}.mjs`,
  )),
  { entryPoints: ['bin/statusline.src.mjs'], outfile: out('bin/impl/statusline.mjs'), ...shared },
  // The status line runs on every UI frame, so an unguarded parse error there is the loudest
  // possible version of this bug.
  launcherTarget(
    launcher('./impl/statusline.mjs', 'the status line', false),
    'statusline.launcher.mjs', 'bin/statusline.mjs',
  ),
  { entryPoints: ['bin/auth.src.mjs'], outfile: out('bin/auth.mjs'), ...shared },
  // No launcher, for the same reason `bin/auth.mjs` has none: launchers exist for the entries
  // the *host* execs on its own (`hooks.json`, `settings.json`), where a parse error on an old
  // Node would be silent. A skill-invoked script is run by a person who is watching, and the
  // runtime floor is already reported by the command they typed.
  //
  // `bin/dashboard.html` is read at runtime rather than imported as a text module, so it does
  // not appear here: importing it would make `bin/dashboard.src.mjs` unloadable by Node, and
  // the suite drives `main()` by importing that file. It also keeps 20 KB of markup out of
  // this bundle's inline sourcemap. The page ships as the tracked sibling it already is.
  { entryPoints: ['bin/dashboard.src.mjs'], outfile: out('bin/dashboard.mjs'), ...shared },
  // The launcher hands the server its own version, because the server cannot read it once
  // relocated: it does `require("../package.json")`, which resolves inside @mubit-ai/mcp and
  // not inside this plugin. Inlined from the tracked sibling manifest, so the value is
  // byte-reproducible and `scripts/set-version.mjs` already keeps it in lockstep.
  {
    entryPoints: ['mcp/src/launch.mjs'],
    outfile: out('mcp/dist/index.js'),
    ...shared,
    external: ['./server.js'],
    define: { __MUBIT_MCP_VERSION__: JSON.stringify(MCP_VERSION) },
  },
  // The server drags in @mubit-ai/sdk -> @grpc/grpc-js, which is CommonJS and reaches for
  // `require` at runtime. esbuild's ESM output defines a `__require` helper that throws
  // ("Dynamic require of X is not supported") unless a real `require` is in scope, so the
  // bundle dies on its first import with no MCP tools registered at all. The banner puts one
  // there. Only this target needs it — nothing else here bundles a CJS dependency tree.
  {
    entryPoints: [MCP_SERVER_ENTRY],
    outfile: out('mcp/dist/server.js'),
    ...shared,
    banner: {
      js: `${shared.banner.js}\n`
        + "import { createRequire as __mubitCreateRequire } from 'node:module';\n"
        + 'const require = __mubitCreateRequire(import.meta.url);',
    },
  },
];

// The MCP server entry is the one target that may NOT be skipped.
//
// Every other entry here is plugin source: it is either on disk or it is not, and skipping
// a hook that has not been written yet is how `npm run build` stays usable across the
// mini-projects. `MCP_SERVER_ENTRY` is different — it is *generated* (tsc output from the
// sibling package), so "missing" is the normal state of a fresh checkout rather than a
// signal that nobody has written it. Warning and skipping there leaves the committed
// `mcp/dist/server.js` untouched, which means both CI gates that rebuild and then run
// `git diff --exit-code` pass while never having rebuilt the server at all — a green build
// that proves nothing, in precisely the place a stale server bundle already shipped once.
//
// The one exception is a checkout where the sibling is not merely uncompiled but absent:
// the generated `claude-plugins` mirror vendors `mcp/dist/server.js` and has no `../mcp` to
// build from, so the target is structurally unbuildable there and the refusal above blocks
// every *other* target with it. `MUBIT_CC_BUILD_SKIP_SERVER=1` opts out explicitly — which
// is the honest shape for this, where a silent skip would not be: the operator states that
// they know the server bundle will not be rebuilt, and the target falls through to the skip
// loop below, which warns and leaves the committed bundle untouched.
if (!has(MCP_SERVER_ENTRY) && process.env.MUBIT_CC_BUILD_SKIP_SERVER !== '1') {
  console.error(
    `[esbuild] ${MCP_SERVER_ENTRY} does not exist.\n`
    + '  mcp/dist/server.js is bundled from the in-repo @mubit-ai/mcp, which is TypeScript and\n'
    + '  must be compiled first:\n'
    + `      ${MCP_SERVER_BUILD}\n`
    + '  Refusing to continue: skipping this target would leave the committed server bundle in\n'
    + '  place and report success.\n'
    + '  If this checkout has no ../mcp at all (the generated claude-plugins mirror vendors the\n'
    + '  server bundle instead), say so: MUBIT_CC_BUILD_SKIP_SERVER=1.');
  process.exit(1);
}

// Entry points are written across several mini-projects, and `npm run build` has to work
// before the last one lands. Skip what is not on disk with a loud warning instead of
// failing the whole build: a missing bundle is already caught by manifests.test.mjs, which
// checks every hooks.json path against hooks/dist/.
const runnable = [];
for (const t of targets) {
  // A `stdin` target has no entry point on disk to check — its source is generated above.
  if (!t.entryPoints) { runnable.push(t); continue; }
  const present = t.entryPoints.filter(has);
  for (const missing of t.entryPoints.filter((e) => !has(e))) {
    console.warn(`[esbuild] skipping ${missing} — not written yet`);
  }
  if (present.length) runnable.push({ ...t, entryPoints: present });
}

const watch = process.argv.includes('--watch');
for (const t of runnable) { if (watch) { (await context(t)).watch(); } else { await build(t); } }
