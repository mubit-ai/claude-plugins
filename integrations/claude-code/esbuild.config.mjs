// Build definition for the mubit-memory Claude Code plugin — build-guide §11.2.
//
// Everything Claude Code executes is a bundled, dependency-free .mjs: `node <path>` on a
// single file is a ~30 ms cold start, where `npx` or a TS loader would cost ~500 ms on
// every PostToolUse (§11.4). The output lives in git (§11.3), so the settings that make
// the build byte-reproducible — minify: false, sourcemap: 'inline' — are pinned here
// rather than left to esbuild's defaults; CI rebuilds and runs `git diff --exit-code`.

import { build, context } from 'esbuild';
import { existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const has = (rel) => existsSync(resolve(ROOT, rel));

const shared = {
  bundle: true, platform: 'node', target: 'node20', format: 'esm',
  minify: false,            // readable stack traces beat 40 KB; nothing ships over a network
  sourcemap: 'inline', legalComments: 'none', logLevel: 'info',
  banner: { js: '// mubit-memory — generated by esbuild. Do not edit; edit hooks/src or lib.' },
};

const HOOKS = ['session-start','prompt-recall','stage-prompt','capture','checkpoint','session-end','drain'];

// ---------------------------------------------------------------------------
// The runtime floor guard (§11.1 engines)
// ---------------------------------------------------------------------------
// The bundles target node20 and use `??` ~40x per file. On an older Node they do not fail —
// they never load, and say nothing: no marker, no log line, no MCP activity, which reads
// exactly like a plugin that was never configured. A guard *inside* those bundles cannot
// help, because a module is parsed in full before its first statement executes; the parse
// error happens first. Nor can the target simply be lowered: all seven entry points use
// top-level await, and node14.8 is the lowest target esbuild will accept for it — still
// above the node12.22 that Debian 11 installs, and short of `fetch` (18+),
// `AbortController` (15+) and `Array.prototype.at` (16.6+) besides.
//
// So the file Claude Code actually executes is this launcher, built for an old runtime, and
// the real bundle moves to `impl/`. The launcher checks the version, and either refuses in a
// sentence or hands off. `hooks.json` and `settings.json` keep naming the same paths.
//
// LAUNCHER_TARGET is load-bearing twice over. It must be >= node12.20, or esbuild rewrites
// `import()` into `require()` and the launcher dies in ESM; and it is what mechanically
// guarantees this source stays parseable on old Node — esbuild fails the build if the
// launcher ever grows syntax that is too new, rather than leaving it to review.
const MIN_NODE_MAJOR = 20;
const LAUNCHER_TARGET = 'node12.20';

/**
 * @param {string} rel  impl path relative to the launcher, e.g. './impl/capture.mjs'
 * @param {string} what name used in the refusal message
 * @param {boolean} hookProtocol emit `{"suppressOutput":true}` on stdout — the hook contract
 *   (lib/hook.mjs: "stdout is ALWAYS a JSON object"). The status line writes a bare line
 *   instead, so for it, silence is the correct no-op.
 *
 * `__mubitLauncherEntry` exists for `bin/statusline.src.mjs`, which runs its body only when
 * it is the process entry — and behind a launcher it no longer literally is. The flag is
 * realm-local rather than an env var, which would leak into every child process a hook
 * spawns. The hook bundles do not consult it; they have no such guard.
 */
const launcher = (rel, what, hookProtocol) => `import { writeSync } from 'fs';
var major = parseInt(String(process.versions.node).split('.')[0], 10);
if (!(major >= ${MIN_NODE_MAJOR})) {
  try {
    writeSync(2, 'mubit-memory requires Node >= ${MIN_NODE_MAJOR} (package.json engines); found v'
      + process.versions.node + '. ${what} is disabled for this session.\\n');
${hookProtocol ? '    writeSync(1, \'{"suppressOutput":true}\');\n' : ''}  } catch (e) { /* a closed pipe is not worth failing a session over */ }
  // 0, never 1: a misconfigured runtime must not fail the user's session.
  process.exit(0);
}
globalThis.__mubitLauncherEntry = ${JSON.stringify(rel)};
import('${rel}').catch(function (err) {
  try {
    writeSync(2, 'mubit-memory: ${what} failed to load: '
      + ((err && err.message) ? err.message : String(err)) + '\\n');
${hookProtocol ? '    writeSync(1, \'{"suppressOutput":true}\');\n' : ''}  } catch (e) { /* ditto */ }
  process.exit(0);
});
`;

/** @param {string} contents @param {string} sourcefile @param {string} outfile */
const launcherTarget = (contents, sourcefile, outfile) => ({
  stdin: { contents, sourcefile, loader: /** @type {const} */ ('js'), resolveDir: ROOT },
  outfile,
  bundle: false,              // the one dynamic import must stay a runtime import, not inlined
  platform: /** @type {const} */ ('node'),
  format: /** @type {const} */ ('esm'),
  target: LAUNCHER_TARGET,
  minify: false, legalComments: /** @type {const} */ ('none'), logLevel: /** @type {const} */ ('info'),
  banner: { js: '// mubit-memory runtime floor guard — generated by esbuild. Do not edit.' },
});

/** The bundled @mubit-ai/mcp server (§8.3). devDependency-only, so build it when installed. */
const MCP_SERVER_ENTRY = 'node_modules/@mubit-ai/mcp/dist/index.js';

const targets = [
  // outExtension is load-bearing: with `outdir`, esbuild names output `<entry>.js` no matter
  // what the entry was called, so hooks/src/capture.mjs becomes hooks/dist/capture.js while
  // hooks.json points at capture.mjs. Every hook silently becomes a dead path — the plugin
  // installs, registers nine hooks, and none of them exist. (Guide §11.2 omits this; the
  // `outfile` targets below are unaffected because they name the extension outright.)
  {
    entryPoints: HOOKS.map((n) => `hooks/src/${n}.mjs`),
    outdir: 'hooks/dist/impl', outbase: 'hooks/src',
    outExtension: { '.js': '.mjs' },
    ...shared,
  },
  // The guards Claude Code actually executes — one per registered path, identical but for
  // the impl each hands off to.
  ...HOOKS.map((n) => launcherTarget(
    launcher(`./impl/${n}.mjs`, `hook ${n}`, true), `${n}.launcher.mjs`, `hooks/dist/${n}.mjs`,
  )),
  { entryPoints: ['bin/statusline.src.mjs'], outfile: 'bin/impl/statusline.mjs', ...shared },
  // The status line runs on every UI frame, so an unguarded parse error there is the loudest
  // possible version of this bug.
  launcherTarget(
    launcher('./impl/statusline.mjs', 'the status line', false),
    'statusline.launcher.mjs', 'bin/statusline.mjs',
  ),
  { entryPoints: ['bin/auth.src.mjs'], outfile: 'bin/auth.mjs', ...shared },
  { entryPoints: ['mcp/src/launch.mjs'], outfile: 'mcp/dist/index.js', ...shared, external: ['./server.js'] },
  // The server drags in @mubit-ai/sdk -> @grpc/grpc-js, which is CommonJS and reaches for
  // `require` at runtime. esbuild's ESM output defines a `__require` helper that throws
  // ("Dynamic require of X is not supported") unless a real `require` is in scope, so the
  // bundle dies on its first import with no MCP tools registered at all. The banner puts one
  // there. Only this target needs it — nothing else here bundles a CJS dependency tree.
  {
    entryPoints: [MCP_SERVER_ENTRY],
    outfile: 'mcp/dist/server.js',
    ...shared,
    banner: {
      js: `${shared.banner.js}\n`
        + "import { createRequire as __mubitCreateRequire } from 'node:module';\n"
        + 'const require = __mubitCreateRequire(import.meta.url);',
    },
  },
];

// Entry points are written across several mini-projects, and `npm run build` has to work
// before the last one lands. Skip what is not on disk with a loud warning instead of
// failing the whole build: a missing bundle is already caught by manifests.test.mjs, which
// checks every hooks.json path against hooks/dist/.
const runnable = [];
for (const t of targets) {
  // A `stdin` target has no entry point on disk to check — its source is generated above.
  if (!t.entryPoints) { runnable.push(t); continue; }
  const present = t.entryPoints.filter(has);
  for (const missing of t.entryPoints.filter((e) => !has(e))) {
    console.warn(`[esbuild] skipping ${missing} — not written yet`);
  }
  if (present.length) runnable.push({ ...t, entryPoints: present });
}

const watch = process.argv.includes('--watch');
for (const t of runnable) { if (watch) { (await context(t)).watch(); } else { await build(t); } }
